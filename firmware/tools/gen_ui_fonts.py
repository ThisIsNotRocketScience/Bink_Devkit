#!/usr/bin/env python3
"""Regenerates core/UiFonts.h: the LCD's fonts, anti-aliased, proportional, 4 bits a pixel.

    pip install pillow
    python3 tools/gen_ui_fonts.py

Needs curl. Downloads Inter, a typeface drawn for screens, under the SIL Open Font License. The font itself is not kept in this
repository; the header carries its copyright notice and licence.
"""
import hashlib
import io
import subprocess
import zipfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT_URL = "https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip"
FONT_SHA256 = "9883fdd4a49d4fb66bd8177ba6625ef9a64aa45899767dde3d36aa425756b11e"
FONT_FILE = "InterVariable.ttf"
LICENSE_FILE = "LICENSE.txt"

OUT = Path(__file__).resolve().parent.parent / "core" / "UiFonts.h"
BRAND_TEXT = "BINK DEVKIT"
BRAND_WIDTH = 220
BRAND_WEIGHT = 800
ASCII = "".join(chr(c) for c in range(32, 127))
FONTS = [  # name, pixel size, weight, characters
    ("kFontSmall", 12, 500, ASCII),
    ("kFontTitle", 15, 650, ASCII),
    ("kFontBig", 36, 600, "+-0123456789"),
]


def download():
    """The font as bytes, and the text of its licence."""
    print("Downloading", FONT_URL)
    data = subprocess.run(["curl", "-fsSL", FONT_URL], stdout=subprocess.PIPE, check=True).stdout
    digest = hashlib.sha256(data).hexdigest()
    if digest != FONT_SHA256:
        raise SystemExit(f"Unexpected download: sha256 {digest}")
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        def find(name):
            return next(n for n in archive.namelist() if n.rsplit("/", 1)[-1] == name)
        return archive.read(find(FONT_FILE)), archive.read(find(LICENSE_FILE)).decode("utf8")


def load(data, size, weight):
    font = ImageFont.truetype(io.BytesIO(data), size)
    axes = font.get_variation_axes()
    font.set_variation_by_axes([weight if b"eight" in a["name"] or a["name"] == "wght" else min(max(size, a["minimum"]), a["maximum"]) for a in axes])
    return font


def glyphs(data, size, weight, chars):
    font = load(data, size, weight)
    ascent, descent = font.getmetrics()
    out = []
    for ch in chars:
        box = font.getbbox(ch, anchor="ls")
        w, h = box[2] - box[0], box[3] - box[1]
        px = []
        if w > 0 and h > 0:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
            px = list(img.getdata())
        out.append((ch, w, h, box[0], box[1] + ascent, round(font.getlength(ch)), px))
    return out, ascent + descent


def main():
    data, license_text = download()
    lines = ["// Generated by tools/gen_ui_fonts.py from Inter. Do not edit.", "/*"]
    lines += [line.rstrip().replace("*/", "* /") for line in license_text.strip().splitlines()]
    lines += ["*/", "#pragma once", '#include "UiGfx.h"', ""]
    brand = 10
    while load(data, brand + 1, BRAND_WEIGHT).getlength(BRAND_TEXT) <= BRAND_WIDTH:
        brand += 1
    fonts = FONTS + [("kFontBrand", brand, BRAND_WEIGHT, "".join(sorted(set(BRAND_TEXT))))]
    for name, size, weight, chars in fonts:
        gl, height = glyphs(data, size, weight, chars)
        bits, table = bytearray(), []
        for ch, w, h, x, y, adv, px in gl:
            table.append(f"{{{len(bits)}, {w}, {h}, {x}, {y}, {adv}}}, // {ch!r}")
            nibbles = [min((p + 8) // 17, 15) for p in px]
            if len(nibbles) % 2:
                nibbles.append(0)
            bits += bytes(nibbles[i] << 4 | nibbles[i + 1] for i in range(0, len(nibbles), 2))
        lines.append(f"static const uint8_t {name}Bits[] = {{")
        for i in range(0, len(bits), 24):
            lines.append("    " + ", ".join(str(b) for b in bits[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const UiGlyph {name}Glyphs[] = {{")
        lines += ["    " + t for t in table]
        lines.append("};")
        lines.append(f'static const UiFont {name} = {{{name}Glyphs, {name}Bits, "{chars.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}", {len(chars)}, {height}}};')
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf8", newline="\n")
    print(OUT, OUT.stat().st_size)


if __name__ == "__main__":
    main()
